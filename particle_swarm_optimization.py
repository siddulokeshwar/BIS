import numpy as np


def fitness(x):
    return np.power(x, 2)

population_size = 10
iterations = 50
inertia = 0.5
cognitive, social = 1.5, 1.5



positions = np.random.uniform(0 , 50, size=population_size)
velocities = np.random.uniform(0, 1, size=population_size)

p_best_positions = np.copy(positions)
p_best_fitnesses = fitness(p_best_positions)

g_best_idx = np.argmin(p_best_fitnesses)
g_best_position = p_best_positions[g_best_idx]
g_best_fitness = p_best_fitnesses[g_best_idx]


print(f"Initial Global Best Position: {g_best_position:.4f}, Fitness: {g_best_fitness:.4f}\n")

for i in range(iterations):
    r1 = np.random.uniform(0, 1, size=population_size)
    r2 = np.random.uniform(0, 1, size=population_size)


    velocities = (inertia * velocities +
                  cognitive * r1 * (p_best_positions - positions) +
                  social * r2 * (g_best_position - positions))


    positions = positions + velocities


    current_fitnesses = fitness(positions)

    improved_mask = current_fitnesses < p_best_fitnesses
    p_best_positions[improved_mask] = positions[improved_mask]
    p_best_fitnesses[improved_mask] = current_fitnesses[improved_mask]

    min_current_idx = np.argmin(p_best_fitnesses)
    if p_best_fitnesses[min_current_idx] < g_best_fitness:
        g_best_position = p_best_positions[min_current_idx]
        g_best_fitness = p_best_fitnesses[min_current_idx]

    if (i + 1) % 10 == 0 or i == 0:
        print(f"Iteration {i+1:02d}/{iterations}: Best Position = {g_best_position:.6f}, Best Fitness = {g_best_fitness:.6f}")

print(f"\nOptimization complete.\nFinal Best Position: {g_best_position:.6f}\nFinal Best Fitness: {g_best_fitness:.6e}")